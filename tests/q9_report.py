"""Regenerate the Q9 case table + actual diffs inside FINDINGS.md (between markers).
Run: uv run python tests/q9_report.py"""
import difflib
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from q9_corpus import CASES  # noqa: E402
from spike_config_roundtrip.config import Config, read_exact  # noqa: E402

BEGIN, END = "<!-- q9:begin (generated by tests/q9_report.py) -->", "<!-- q9:end -->"


def run(c):
    with tempfile.TemporaryDirectory() as d:
        f = Path(d) / "c.yml"
        with open(f, "w", encoding="utf-8", newline="") as fh:
            fh.write(c.before)
        try:
            cfg = Config(f)
            strat = []
            for p, v in c.ops:
                cfg.set(p, v)
                strat.append(cfg.last_write_strategy)
            after, err = read_exact(str(f)), None
        except Exception as e:
            after, strat, err = read_exact(str(f)), ["error"], f"{type(e).__name__}: {str(e).splitlines()[0]}"
    return after, strat, err


def show(s):
    return s.replace("\r", "\\r").replace("\t", "\\t")


def lines(text):
    out = [show(l[:-1] if l.endswith("\n") else l) + "\n" for l in text.splitlines(True)]
    if text and not text.endswith("\n"):
        out[-1] = out[-1][:-1] + "   [no EOL at end of file]\n"
    return out


def cell(s):
    return s.replace("|", "\\|")


def main():
    rows, diffs = [], []
    for c in CASES:
        after, strat, err = run(c)
        s = "splice" if all(x == "splice" for x in strat) else ("error" if err else "dump")
        ok = after == c.after
        surgical = "yes" if ok and s == "splice" else ("n/a" if c.expect == "error" and err else "NO")
        if c.expect == "error":
            surgical = "n/a (rejected)" if err else "NO"
        d = "".join(difflib.unified_diff(
            lines(c.before), lines(after), "before", "after", n=1))
        ch = sum(1 for l in d.splitlines() if l[:1] in "+-" and not l.startswith(("+++", "---")))
        rows.append(f"| {c.group} | {cell(c.name)} | {s} | {surgical} | {ch} | {cell(c.note or '')}{cell(' ' + err) if err else ''} |")
        diffs.append(f"**{c.group} / {c.name}** (`{', '.join(f'set {p}' for p, _ in c.ops)}`)\n\n```diff\n{d or '(no change)\n'}```\n")
    out = [BEGIN, "", "| group | case | strategy | surgical | changed lines | note |", "|---|---|---|---|---|---|", *rows,
           "", f"**{sum(1 for r in rows if '| yes |' in r)} of {len(rows)} cases surgical.**", "",
           "<details><summary>Actual diffs for every case (generated)</summary>", "", *diffs, "</details>", "", END]
    fp = Path(__file__).parent.parent / "FINDINGS.md"
    txt = fp.read_text()
    if BEGIN in txt:
        txt = txt[: txt.index(BEGIN)] + "\n".join(out) + txt[txt.index(END) + len(END):]
    else:
        txt = txt.replace("_Cases and results are being filled in below as each group is done._",
                          "_Cases and results are being filled in below as each group is done._\n\n" + "\n".join(out))
    fp.write_text(txt)
    print("\n".join(rows))


if __name__ == "__main__":
    main()
